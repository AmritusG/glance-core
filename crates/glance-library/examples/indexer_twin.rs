//! The Rust side of the indexer cross-test (tools/swift-library-oracle/indexer-crosstest.sh): the same script
//! commands and output lines as Swift MaCrate's IndexerOracle (tools/swift-library-oracle/IndexerOracle.swift), run
//! by glance-library's indexer, plus the scenario's library tree, its mutations between runs, and the comparison
//! of the two resulting databases (glance-library's `dump`, wall-clock stamps masked).
//!
//!   cargo run --release -p glance-library --example indexer_twin -- <mode> <arg> …
//!     gen <lib>                      the scenario tree under <lib> (roots <lib>/A and <lib>/B), from glance-core's
//!                                    tests/fixtures and generated bytes; every file time fixed
//!     mutate <1|2> <lib>             the changes between runs (renames, moves, deletes, new, changed, sidecars)
//!     run <library.sqlite> <script>  as IndexerOracle's `run`
//!     compare <a.sqlite> <b.sqlite> <t0> <t1>
//!                                    dump both, mask created_at / updated_at stamped between t0 and t1 (seconds
//!                                    since 1970, the runs' wall-clock window), print per-table differences
//!     ascend <input>                 as IndexerOracle's `ascend`
//!     thumb <clip> <premultiplied|straight> <out.rgba>   as IndexerOracle's `thumb` (glance-library's extractor)
//!     stats <in.rgba> <w> <h> <premultiplied|straight>   as IndexerOracle's `stats`
